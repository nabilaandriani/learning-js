/**
 * Variabel awal adalah nilai variabel sebelum looping dilakukan. 
 * Test kondisi adalah evaluasi dari looping, jika bernilai false, looping akan berhenti. 
 * Increment adalah nilai variabel yang bertambah setiap looping dilakukan. 
 */

for (let i = 0; i < 5; i++) {
  console.log(`Angka ke-${i} adalah ${i}`);
}
//output:
// Angka ke-0 adalah 0
// Angka ke-1 adalah 1
// Angka ke-2 adalah 2
// Angka ke-3 adalah 3
// Angka ke-4 adalah 4 

